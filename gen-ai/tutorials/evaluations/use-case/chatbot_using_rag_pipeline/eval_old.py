import asyncio
import os

from dotenv import load_dotenv
from gllm_datastore.vector_data_store import ChromaVectorDataStore
from gllm_evals import LLMTestCase, evaluate
from gllm_evals.dataset.dict_dataset import DictDataset
from gllm_evals.evaluator.geval_generation_evaluator import GEvalGenerationEvaluator
from gllm_evals.experiment_tracker.csv_experiment_tracker import CSVExperimentTracker
from gllm_generation.response_synthesizer import ResponseSynthesizer
from gllm_inference.em_invoker.openai_em_invoker import OpenAIEMInvoker
from gllm_inference.lm_invoker import build_lm_invoker
from gllm_pipeline.steps import step
from gllm_retrieval.retriever.vector_retriever import BasicVectorRetriever

load_dotenv()

# Create components
em_invoker = OpenAIEMInvoker(os.getenv("EMBEDDING_MODEL"))
data_store = ChromaVectorDataStore(
    collection_name="documents",
    client_type="persistent",
    persist_directory="data",
    embedding=em_invoker,
)
retriever = BasicVectorRetriever(data_store)
response_synthesizer = ResponseSynthesizer.preset.stuff(os.getenv("LANGUAGE_MODEL"))

# Create the pipeline
retrieve_step = step(
    component=retriever,
    input_map={"query": "user_query", "top_k": "top_k"},
    output_state="chunks",
)
synthesize_step = step(
    component=response_synthesizer,
    input_map={"query": "user_query", "chunks": "chunks"},
    output_state="response",
)
e2e_pipeline = retrieve_step | synthesize_step

# Step 2: Prepare Dataset
# Load from CSV — each row has "query" and "expected_output".
# actual_output and retrieved_context are generated by the pipeline below.
DATASET = DictDataset.from_csv("data/eval_dataset.csv").load()
OUTPUT_DIR = "results"

async def run_pipeline(query: str) -> tuple[str, str]:
    """Run the RAG pipeline for a single query.

    Returns:
        (actual_output, retrieved_context)
    """
    state = {"user_query": query}
    config = {"top_k": 5}
    result = await e2e_pipeline.invoke(state, config)
    response = result["response"]
    chunks = result.get("chunks", [])
    retrieved_context = "\n".join(chunk.content for chunk in chunks)
    return response, retrieved_context


async def main():
    # Step 4: Run the pipeline for every case concurrently
    pipeline_results = await asyncio.gather(
        *[run_pipeline(row["query"]) for row in DATASET]
    )

    # Build LLMTestCase list — CSV provides input/expected_output,
    # pipeline provides actual_output/retrieved_context
    data = [
        LLMTestCase(
            input=row["query"],
            actual_output=actual_output,
            expected_output=row["expected_output"],
            retrieved_context=retrieved_context,  # required for groundedness
        )
        for row, (actual_output, retrieved_context) in zip(DATASET, pipeline_results)
    ]

    judge_model = build_lm_invoker(
        "google/gemini-3-flash-preview",
        os.getenv("GOOGLE_API_KEY"),
    )
    tracker = CSVExperimentTracker(
        project_name="rag-chatbot-eval",
        output_dir=OUTPUT_DIR,
        include_eval_result=True,
    )
    experiment_result = await evaluate(
        data=data,
        evaluators=[GEvalGenerationEvaluator(models=judge_model)],
        experiment_tracker=tracker,
    )
    print(experiment_result)


if __name__ == "__main__":
    asyncio.run(main())